router = APIRouter(prefix="/vision", tags=["image-recognition"])


def out(o: ImageObservation):
    model_name = getattr(o, "model_name", None) or "color-heuristic-v1"
    provider_name = getattr(o, "provider", None) or "heuristic"
    return {
        "id": o.id,
        "schedule_id": o.schedule_id,
        "menu_item_id": o.menu_item_id,
        "width": o.width,
        "height": o.height,
        "format": o.fmt,
        "predicted_label": o.predicted_label,
        "confidence": o.confidence,
        "scores": o.scores,
        "corrected_label": o.corrected_label,
        "final_label": o.corrected_label or o.predicted_label,
        "quantity_kg": o.quantity_kg,
        "status": o.status,
        "created_at": o.created_at,
        "provider": provider_name,
        "model": model_name,
        "disclaimer": (
            f"Visual classification suggestion generated by {model_name} ({provider_name}). "
            "Confidence measures image recognition only — weight and food-safety must be verified by a human operator."
        ),
    }


@router.get("/labels")
def labels(ctx: Ctx = Depends(need("mess_admin", "kitchen"))):
    return V.LABELS


@router.post("/upload", status_code=201)
async def upload(
    file: UploadFile = File(...),
    schedule_id: Optional[int] = Form(None),
    menu_item_id: Optional[int] = Form(None),
    ctx: Ctx = Depends(need("mess_admin", "kitchen")),
    db: Session = Depends(get_db),
):
    rate_limit(f"vision_upload:{ctx.user.id}", 30, 60)
    data = await file.read(settings.max_upload_mb * 1024 * 1024 + 1)
    img, fmt, clean_bytes = V.validate_and_process(data)

    if schedule_id:
        s = db.get(MealSchedule, schedule_id)
        if not s or s.institution_id != ctx.inst_id:
            raise HTTPException(404, "Schedule not found")
    if menu_item_id:
        m = db.get(MenuItem, menu_item_id)
        if not m or m.institution_id != ctx.inst_id:
            raise HTTPException(404, "Dish not found")
        if not is_eligible_menu_item(m):
            raise HTTPException(422, "Image observations can only be linked to active vegetarian dishes")

    classifier = V.get_classifier()
    label, conf, scores, provider_name, model_name = classifier.classify(img, clean_bytes)

    saved_filename = V.save_image_file(clean_bytes, fmt)

    o = ImageObservation(
        institution_id=ctx.inst_id,
        schedule_id=schedule_id,
        menu_item_id=menu_item_id,
        file_name=saved_filename,
        width=img.width,
        height=img.height,
        fmt=fmt,
        size_bytes=len(clean_bytes),
        predicted_label=label,
        confidence=conf,
        scores=scores,
        provider=provider_name,
        model_name=model_name,
        created_by=ctx.user.id,
    )
    db.add(o)
    db.flush()
    audit(db, ctx.user, "upload_image", "image_observation", o.id, f"provider={provider_name}")
    db.commit()
    return out(o)


@router.get("")
def list_obs(ctx: Ctx = Depends(need("mess_admin", "kitchen")), db: Session = Depends(get_db)):
    return [out(o) for o in db.query(ImageObservation).filter_by(institution_id=ctx.inst_id).order_by(ImageObservation.id.desc()).limit(100)]


def _get(db: Session, ctx: Ctx, oid: int) -> ImageObservation:
    o = db.get(ImageObservation, oid)
    if not o or o.institution_id != ctx.inst_id:
        raise HTTPException(404, "Observation not found")
    return o


@router.get("/{oid}/image")
def image(oid: int, ctx: Ctx = Depends(need("mess_admin", "kitchen")), db: Session = Depends(get_db)):
    o = _get(db, ctx, oid)
    content = storage.get_file(o.file_name)
    if not content:
        raise HTTPException(404, "Image file not found in storage")
    return Response(content=content, media_type="image/jpeg")


@router.delete("/{oid}")
def delete_observation(oid: int, ctx: Ctx = Depends(need("mess_admin")), db: Session = Depends(get_db)):
    """Deletes observation and removes orphaned image file from storage."""
    o = _get(db, ctx, oid)
    filename = o.file_name
    db.delete(o)
    db.commit()
    V.delete_image_file(filename)
    audit(db, ctx.user, "delete_image_observation", "image_observation", oid)
    return {"ok": True}


class CorrectIn(BaseModel):
    label: str


@router.patch("/{oid}/correct")
def correct(oid: int, b: CorrectIn, ctx: Ctx = Depends(need("mess_admin", "kitchen")), db: Session = Depends(get_db)):
    o = _get(db, ctx, oid)
    if b.label not in V.LABELS:
        raise HTTPException(422, "Unsupported label")
    if o.status == "confirmed":
        raise HTTPException(409, "Already confirmed")
    o.corrected_label = b.label
    audit(db, ctx.user, "correct_image_label", "image_observation", o.id, b.label)
    db.commit()
    return out(o)


class ConfirmIn(BaseModel):
    quantity_kg: float = Field(gt=0, le=1000)
    edible_kg: float = Field(default=0, ge=0)


@router.post("/{oid}/confirm")
def confirm(oid: int, b: ConfirmIn, ctx: Ctx = Depends(need("mess_admin", "kitchen")), db: Session = Depends(get_db)):
    o = _get(db, ctx, oid)
    if o.status == "confirmed":
        raise HTTPException(409, "Already confirmed")
    if b.edible_kg > b.quantity_kg:
        raise HTTPException(422, "Edible quantity cannot exceed the total quantity")
    if o.menu_item_id and not is_eligible_menu_item(db.get(MenuItem, o.menu_item_id)):
        raise HTTPException(409, "Legacy non-vegetarian observations are preserved and cannot enter current waste records")
    o.quantity_kg, o.status = b.quantity_kg, "confirmed"
    if o.schedule_id and o.menu_item_id:
        db.add(
            WasteRecord(
                schedule_id=o.schedule_id,
                menu_item_id=o.menu_item_id,
                leftover_qty=b.quantity_kg,
                edible_qty=b.edible_kg,
                inedible_qty=b.quantity_kg - b.edible_kg,
                source="image",
                observation_id=o.id,
                recorded_by=ctx.user.id,
                notes=f"image: {o.corrected_label or o.predicted_label}",
            )
        )
    audit(db, ctx.user, "confirm_image", "image_observation", o.id)
    db.commit()
    return out(o)
